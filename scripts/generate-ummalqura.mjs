// Generates src/dates/ummalqura-data.ts from the Umm al-Qura calendar bundled with ICU
// (Intl 'islamic-umalqura', which ships the official Umm al-Qura table).
// Run: node scripts/generate-ummalqura.mjs
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const FIRST_YEAR = 1343;
const LAST_YEAR = 1500;
const DAY = 86_400_000;

const fmt = new Intl.DateTimeFormat('en-u-ca-islamic-umalqura-nu-latn', {
  year: 'numeric',
  month: 'numeric',
  day: 'numeric',
  timeZone: 'UTC',
});
const hijriOf = (dayNumber) => {
  const parts = fmt.formatToParts(new Date(dayNumber * DAY));
  const get = (t) => Number(parts.find((p) => p.type === t).value);
  return { year: get('year'), month: get('month'), day: get('day') };
};

// Scan from well before 1 Muharram FIRST_YEAR to after the end of LAST_YEAR.
let d = Date.UTC(1924, 5, 1) / DAY;
const end = Date.UTC(2078, 0, 31) / DAY;
const starts = []; // { year, month, dayNumber }
for (; d <= end; d++) {
  const h = hijriOf(d);
  if (h.day === 1 && h.year >= FIRST_YEAR && h.year <= LAST_YEAR + 1) starts.push({ ...h, dayNumber: d });
}

const epoch = starts[0];
if (epoch.year !== FIRST_YEAR || epoch.month !== 1) throw new Error('scan did not start at 1 Muharram');

const years = [];
for (let y = FIRST_YEAR; y <= LAST_YEAR; y++) {
  let bits = 0;
  for (let m = 1; m <= 12; m++) {
    const i = starts.findIndex((s) => s.year === y && s.month === m);
    const len = starts[i + 1].dayNumber - starts[i].dayNumber;
    if (len !== 29 && len !== 30) throw new Error(`bad month length ${y}/${m}: ${len}`);
    if (len === 30) bits |= 1 << (m - 1);
  }
  years.push(bits);
}

const out = `// GENERATED by scripts/generate-ummalqura.mjs — do not edit by hand.
// Source: Umm al-Qura calendar as bundled in ICU (Intl 'islamic-umalqura').

/** First Hijri year covered. */
export const UMQ_FIRST_YEAR = ${FIRST_YEAR};
/** Last Hijri year covered. */
export const UMQ_LAST_YEAR = ${LAST_YEAR};
/** Day number (days since 1970-01-01 UTC) of 1 Muharram ${FIRST_YEAR}. */
export const UMQ_EPOCH_DAY = ${epoch.dayNumber};
/** One entry per year; bit (m-1) set ⇒ month m has 30 days, else 29. */
export const UMQ_MONTH_BITS: readonly number[] = [
${years.map((b, i) => `  0x${b.toString(16).padStart(3, '0')}, // ${FIRST_YEAR + i}`).join('\n')}
];
`;

const target = fileURLToPath(new URL('../src/dates/ummalqura-data.ts', import.meta.url));
writeFileSync(target, out);
console.log(`wrote ${years.length} years (${FIRST_YEAR}–${LAST_YEAR}), epoch day ${epoch.dayNumber}`);
